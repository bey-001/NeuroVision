def build_robust_brain_mask(image):
    """FLAIR (N4 sonrası) üzerinden 3 aşamalı, delik doldurulmuş beyin maskesi üretir.

    1) Otsu: kaba beyin/kafa vs arka plan ayrımı.
    2) Morphological Closing: Otsu'nun bıraktığı küçük boşlukları/kopuklukları
       kapatır (ör. damar/BOS bölgelerinde lokal düşük sinyal nedeniyle
       oluşan delikler, kenarlardaki tırtıklı kopukluklar).
    3) Binary Fill Holes: kapalı sınır içinde kalan tüm iç boşlukları
       (ventriküller dahil) doldurarak tek parça, katı bir beyin hacmi verir.

    N4'ün kendi içindeki ham Otsu maskesinden farklı olarak bu maske
    segmentasyon / FCM gibi sonraki adımlarda "beyin dokusu" tanımı olarak
    kullanılmak üzere tasarlandı.
    """
    otsu_mask = sitk.OtsuThreshold(image, 0, 1, 200)

    closed_mask = sitk.BinaryMorphologicalClosing(
        otsu_mask, [CLOSING_RADIUS_MM] * image.GetDimension(), sitk.sitkBall
    )

    filled_mask = sitk.BinaryFillhole(
        closed_mask, fullyConnected=FILL_HOLES_FULLY_CONNECTED
    )

    return otsu_mask, closed_mask, filled_mask


