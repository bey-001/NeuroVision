def get_orientation_code(image) -> str:
    """Görüntünün mevcut yönelim kodunu (LPI, RAI, ...) direction matrix'ten çıkarır."""
    try:
        return sitk.DICOMOrientImageFilter_GetOrientationFromDirectionCosines(
            image.GetDirection()
        )
    except Exception:
        return "UNKNOWN"


def reorient_image(image, orientation: str = TARGET_ORIENTATION):
    """Görüntüyü hedef koordinat yönelimine (LPS) çevirir."""
    orient_filter = sitk.DICOMOrientImageFilter()
    orient_filter.SetDesiredCoordinateOrientation(orientation)
    return orient_filter.Execute(image)


def resample_to_spacing(image, target_spacing=TARGET_SPACING, is_mask: bool = False):
    """Görüntüyü kendi grid'i üzerinde hedef spacing'e resample eder.
    Sadece referans (FLAIR) için kullanılır."""
    original_spacing = image.GetSpacing()
    original_size = image.GetSize()

    new_size = [
        max(1, int(round(osz * ospc / tspc)))
        for osz, ospc, tspc in zip(original_size, original_spacing, target_spacing)
    ]

    resampler = sitk.ResampleImageFilter()
    resampler.SetOutputSpacing(target_spacing)
    resampler.SetSize(new_size)
    resampler.SetOutputDirection(image.GetDirection())
    resampler.SetOutputOrigin(image.GetOrigin())
    resampler.SetTransform(sitk.Transform(3, sitk.sitkIdentity))
    resampler.SetDefaultPixelValue(0)
    resampler.SetInterpolator(MASK_INTERPOLATOR if is_mask else IMAGE_INTERPOLATOR)

    result = resampler.Execute(image)
    return _postprocess(result, is_mask)


def resample_to_reference(image, reference, is_mask: bool = False):
    """Görüntüyü verilen referans grid'e (standardize edilmiş FLAIR) hizalar.
    T1 / T2 / LESION için kullanılır -> tüm modaliteler birebir aynı grid'e oturur."""
    resampler = sitk.ResampleImageFilter()
    resampler.SetReferenceImage(reference)
    resampler.SetTransform(sitk.Transform(3, sitk.sitkIdentity))
    resampler.SetDefaultPixelValue(0)
    resampler.SetInterpolator(MASK_INTERPOLATOR if is_mask else IMAGE_INTERPOLATOR)

    result = resampler.Execute(image)
    return _postprocess(result, is_mask)


def _postprocess(image, is_mask: bool):
    """BSpline overshoot / mask encoding temizliği."""
    if is_mask:
        # Nearest neighbor label değerlerini korur ama farklı encoding'lere
        # (0/1, 0/255, vb.) karşı garanti olsun diye açıkça binarize ediyoruz.
        array = sitk.GetArrayFromImage(image)
        binary = (array > 0).astype(np.uint8)
        out = sitk.GetImageFromArray(binary)
        out.CopyInformation(image)
        return out
    else:
        # BSpline negatif overshoot üretebilir; MRI intensity fiziksel olarak >= 0.
        return sitk.Clamp(image, lowerBound=0.0)


