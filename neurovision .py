def find_modality_file(case_dir: Path, modality: str) -> Path | None:
    """
    Belirtilen modality için tek, deterministik bir dosya döner.
    Uzantı önceliği: .nhdr > .nii > .nii.gz
    'LESION' aranırken 'LESION_BYCHB' dosyaları otomatik hariç tutulur.
    """
    keyword = MODALITY_KEYWORDS[modality]
    exclude = "bychb" if modality == "LESION" else None

    for ext in [".nhdr", ".nii", ".nii.gz"]:
        files = sorted(case_dir.glob(f"*{ext}"))
        files = [f for f in files if keyword in f.name.lower()]
        if exclude:
            files = [f for f in files if exclude not in f.name.lower()]
        if files:
            return files[0]
    return None


def find_all_modalities(case_dir: Path) -> dict:
    """Bir case için tüm modaliteleri (FLAIR, T1, T2, LESION, LESION_BYCHB) bulur."""
    return {mod: find_modality_file(case_dir, mod) for mod in MODALITY_KEYWORDS}


def read_image(path: Path):
    """Read medical image using SimpleITK. Returns (image, error_message)."""
    try:
        image = sitk.ReadImage(str(path))
        return image, None
    except Exception as exc:
        return None, str(exc)


def load_image_array(path: Path):
    """Read image and also return the NumPy array. Returns (image, array, error)."""
    image, err = read_image(path)
    if image is None:
        return None, None, err
    return image, sitk.GetArrayFromImage(image), None


def image_metadata(image) -> dict:
    """Extract relevant geometry metadata (JSON-safe lists, not tuples)."""
    return {
        "size": [int(x) for x in image.GetSize()],
        "spacing": [float(x) for x in image.GetSpacing()],
        "origin": [float(x) for x in image.GetOrigin()],
        "direction": [float(x) for x in image.GetDirection()],
    }


def tuple_close(a, b, tolerance: float = GEOMETRY_TOLERANCE) -> bool:
    """Compare two numeric tuples/lists within a tolerance."""
    if len(a) != len(b):
        return False
    return all(abs(x - y) <= tolerance for x, y in zip(a, b))


