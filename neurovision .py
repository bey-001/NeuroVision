def get_site(case_id: str) -> str:
    """Infer acquisition site from case ID."""
    if case_id.startswith("CHB_train_Case"):
        return "CHB"
    if case_id.startswith("UNC_train_Case"):
        return "UNC"
    return "UNKNOWN"


def find_case_directories(root: Path = EXTRACTED_DIR) -> list[Path]:
    """Find CHB and UNC training case directories."""
    case_dirs = []
    for path in root.iterdir():
        if not path.is_dir():
            continue
        if path.name.startswith("CHB_train_Case") or path.name.startswith("UNC_train_Case"):
            case_dirs.append(path)
    return sorted(case_dirs)


