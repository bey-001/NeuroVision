    t1_path = find_modality_file(case_dir, "T1")
    t2_path = find_modality_file(case_dir, "T2")
    lesion_path = find_modality_file(case_dir, "LESION")

    # Lesion mask'i clip edilmemiş olabilir; CLIPPED_DIR'da bulunamazsa
    # ham veri klasöründen (EXTRACTED_DIR) fallback olarak dene
    if lesion_path is None and raw_case_dir is not None:
        lesion_path = find_modality_file(raw_case_dir, "LESION")

    missing = [
        name for name, p in
        [("FLAIR", flair_path), ("T1", t1_path), ("T2", t2_path), ("LESION", lesion_path)]
        if p is None
    ]
