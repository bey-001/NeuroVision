def build_brain_mask(image):
    """Otsu eşiklemesiyle beyin/kafa maskesi üretir (arka plan = 0 varsayımıyla).

    N4, bias field'i sadece maske içindeki dokudan tahmin eder; maskenin
    dışındaki (arka plan) voksellerin etkisi tamamen elenir.

    NOT: Bu, N4'ün kendi iç hesabı için kullandığı HAM/hızlı bir Otsu
    maskesidir. Segmentasyon/FCM gibi sonraki adımlar için daha güvenilir,
    delik doldurulmuş bir maske bir sonraki hücrede (ROBUST BRAIN MASK)
    ayrıca üretiliyor.
    """
    mask = sitk.OtsuThreshold(image, 0, 1, 200)
    return mask


def run_n4_correction(image):
    """Görüntüyü N4BiasFieldCorrectionImageFilter ile düzeltir.

    Hız için: (1) görüntü ve maske shrink edilir, (2) log-bias-field bu
    küçültülmüş grid üzerinde kestirilir, (3) bias field orijinal
    çözünürlükte yeniden hesaplanıp tam görüntüye uygulanır.
    """
    image_f32 = sitk.Cast(image, sitk.sitkFloat32)
    mask = build_brain_mask(image_f32)

    if N4_SHRINK_FACTOR > 1:
        image_shrunk = sitk.Shrink(image_f32, [N4_SHRINK_FACTOR] * image_f32.GetDimension())
        mask_shrunk = sitk.Shrink(mask, [N4_SHRINK_FACTOR] * mask.GetDimension())
    else:
        image_shrunk = image_f32
        mask_shrunk = mask

    corrector = sitk.N4BiasFieldCorrectionImageFilter()
    corrector.SetMaximumNumberOfIterations(N4_MAX_ITERATIONS)
    corrector.SetConvergenceThreshold(N4_CONVERGENCE_THRESHOLD)

    _ = corrector.Execute(image_shrunk, mask_shrunk)

    log_bias_field_full = corrector.GetLogBiasFieldAsImage(image_f32)
    bias_field_full = sitk.Exp(log_bias_field_full)
    corrected_full = image_f32 / bias_field_full

    corrected_full = sitk.Clamp(corrected_full, lowerBound=0.0)

    bias_field_full.CopyInformation(image_f32)
    mask.CopyInformation(image_f32)

    return corrected_full, mask, bias_field_full


